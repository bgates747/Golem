#!/usr/bin/env python3
"""Stage the dedicated Oryx fixture and verify it headlessly, leaving it stopped."""
from pathlib import Path
import hashlib
import json
import subprocess

TASK = Path(__file__).resolve().parent
PROJECT = TASK.parents[2]
HOST = 'oryx-linuxlite'
ROOT = 'Agon/mystuff/golem'


def main():
    accepted = json.loads((TASK.parent/'GOLEM-007/oryx-review.json').read_text())
    pinned = {key: value for key, value in accepted['sha256'].items()
              if key in ('.emulator/fab-agon-emulator', '.emulator/fab-agon-emulator.bin',
                         '.emulator/firmware/vdp_platform.so', '.emulator/mos_platform.bin',
                         '.emulator/mos_platform.map')}
    subprocess.run(['ssh', '-o', 'BatchMode=yes', HOST,
                    'mkdir -p ~/Agon/mystuff/golem/docs/tasks/GOLEM-014/build '
                    '~/Agon/mystuff/golem/.emulator/sdcard/golem-014'], check=True)
    files = [TASK/'expected.dat', TASK/'emulator-checks.json', TASK/'verify_review.py']
    subprocess.run(['scp', *map(str, files), f'{HOST}:{ROOT}/docs/tasks/GOLEM-014/'], check=True)
    subprocess.run(['scp', str(TASK/'build/probe.bin'),
                    f'{HOST}:{ROOT}/.emulator/sdcard/golem-014/probe.bin'], check=True)
    hashes = {f'docs/tasks/GOLEM-014/{p.name}': hashlib.sha256(p.read_bytes()).hexdigest()
              for p in files}
    hashes['.emulator/sdcard/golem-014/probe.bin'] = hashlib.sha256((TASK/'build/probe.bin').read_bytes()).hexdigest()
    script = 'PINNED = ' + repr(pinned) + '\nFIXTURE = ' + repr(hashes) + '\n' + r'''
from pathlib import Path
import hashlib, json, os, signal, subprocess, time
root = Path.home()/'Agon/mystuff/golem'
profile = root/'.emulator'
task = root/'docs/tasks/GOLEM-014'
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
assert not (profile/'fab-agon-emulator').is_symlink()
assert 'Generated by agon-dev-env setup_emulator.py' in (profile/'fab-agon-emulator').read_text()
runtime = (profile/'fab-agon-emulator.bin').resolve()
for proc in Path('/proc').glob('[0-9]*'):
    try:
        if (proc/'exe').resolve() == runtime: raise RuntimeError('Close the emulator before staging')
    except (FileNotFoundError, PermissionError): pass
for key, expected in {**PINNED, **FIXTURE}.items():
    assert sha(root/key) == expected, key
startup = profile/'sdcard/autoexec.txt'
previous = startup.read_bytes() if startup.exists() else None
backup = task/'build/previous-autoexec.txt'
if previous is not None and not backup.exists(): backup.write_bytes(previous)
startup.write_bytes(b'SET KEYBOARD 1\r\ncd /golem-014\r\nload probe.bin\r\nrun .\r\n')
result = profile/'sdcard/golem-014/results.dat'
result.unlink(missing_ok=True)
env = {k:v for k,v in os.environ.items() if k not in ('LD_PRELOAD', 'BASH_ENV')}
env.update(SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy')
started = time.monotonic()
mapped = set()
actual = None
process = None
try:
    with (task/'build/emulator.log').open('w') as log:
        process = subprocess.Popen(['./fab-agon-emulator', '--renderer', 'sw'],
            cwd=profile, env=env, stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        expected = (task/'expected.dat').read_bytes()
        while not result.exists() or result.stat().st_size < len(expected):
            if process.poll() is not None: raise RuntimeError('Emulator exited before results')
            maps = Path(f'/proc/{process.pid}/maps').read_text()
            mapped.update(Path(line.split(maxsplit=5)[5]).resolve() for line in maps.splitlines()
                          if '/vdp_' in line and '.so' in line)
            if mapped:
                assert mapped == {(profile/'firmware/vdp_platform.so').resolve()}
                actual = Path(f'/proc/{process.pid}/exe').resolve()
                assert actual == runtime
            if time.monotonic()-started > 180: raise TimeoutError('See build/emulator.log')
            time.sleep(0.05)
finally:
    if process and process.poll() is None:
        os.killpg(process.pid, signal.SIGTERM)
        try: process.wait(timeout=5)
        except subprocess.TimeoutExpired: os.killpg(process.pid, signal.SIGKILL); process.wait()
assert mapped and actual
assert result.read_bytes() == expected
subprocess.run([str(root/'.venv/bin/python'), str(task/'verify_review.py')], check=True)
for key, expected_hash in {**PINNED, **FIXTURE}.items(): assert sha(root/key) == expected_hash
observed_hash = sha(result)
result.unlink() # Human review must produce fresh observations.
report = dict(host=os.uname().nodename, architecture=os.uname().machine,
    profile=str(profile), pass_headless=True, checks=json.loads((task/'emulator-checks.json').read_text())['checks'], observed_bytes=len(expected),
    execution_seconds=round(time.monotonic()-started,3), runtime_identity=PINNED,
    fixture_identity=FIXTURE, startup_sha256=sha(startup), observed_sha256=observed_hash,
    executed_fab=str(actual), loaded_vdp=str(next(iter(mapped))),
    human_validation='pending', graphical_emulator_launched=False,
    emulator_stopped=True, result_removed_for_fresh_human_review=True,
    previous_startup_backup=str(backup))
(task/'oryx-review.json').write_text(json.dumps(report,indent=2)+'\n')
print('Oryx fixture passed headless verification and is stopped; human review pending.')
'''
    subprocess.run(['ssh', '-o', 'BatchMode=yes', HOST, 'python3 -'], input=script,
                   text=True, check=True)
    subprocess.run(['scp', f'{HOST}:{ROOT}/docs/tasks/GOLEM-014/oryx-review.json',
                    str(TASK/'oryx-review.json')], check=True)


if __name__ == '__main__':
    main()
